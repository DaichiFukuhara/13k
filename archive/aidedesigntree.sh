+# 判断基準の蓄積
+
+受け入れ条件（何をもって終わりとするか）と分割条件（どこで切るか）は、AI が判断する。
+人間は毎回決めない。代わりに、**判断を記録し、後から覆せる**ようにする。
+
+ここが、このハーネスで人間の訂正が入る唯一の場所である。
+分割の提案とその基準が AI 側にあるため、ここを持たないと基準を外から直せなくなる
+（承認は人間が行うが、承認は個々の提案に対する可否であって、基準そのものは直せない）。
+
+## 貯めるのは基準ではなく判断
+
+基準だけを貯めると、間違った基準もそのまま強化される。
+記録するのは判断そのものと、**その後どうなったか**の対で、価値があるのは覆った記録のほう。
+
+[precedents.md](precedents.md) に、新しいものを上に足す。
+
+```md
+### <日付> <一文で判断内容>
+
+- 場面: どのノードの、どの判断か
+- 判断: どうしたか
+- 根拠: なぜそうしたか
+- 結果: 後から分かったこと。まだ分からなければ `未確定`
+- 訂正: 人間が覆した場合の内容。無ければ空
+```
+
+## 使い方
+
+- 受け入れ条件を書くとき、分割の可否を決めるとき、**先に precedents.md を読む**。
+- 過去の判断と矛盾する判断をするなら、その理由を新しいエントリに書く。
+  黙って変えない。
+- `訂正` が入っているエントリは、AI 自身の判断より強い。同じ場面では訂正に従う。
+
+## 誰が書くか
+
+- 判断した役割（split / review）が、判断と同時に `結果: 未確定` で書く。
+- `結果` は後から埋める。実装が終わったとき、分割が裏目に出たとき、人間が指摘したとき。
+- 人間はいつでも `訂正` を追記してよい。既存の行は書き換えない。
+
+## 数が増えたら
+
+エントリが増えて読み切れなくなったら、そのときに要約する。
+先に分類や体系を作らない。**どういう判断が繰り返し出てくるかは、貯まるまで分からない。**
