+# 役割: 前検査（precheck）
+
+分割提案を人間へ出す前に、**提案した AI とは別実装の AI** が確認する。
+現時点の担当は Codex（提案は Claude）。
+
+拒否権は無い。指摘を付けて人間へ渡すだけで、承認するかは人間が決める。
+「別実装」であることが要件。同じモデルだと同じ見落としをする。
+
+## 入力
+
+- 対象ノードの `index.md`（分割提案を含む）
+- 祖先チェーン
+- `harness/` 一式
+- `harness/criteria/precedents.md`
+
+兄弟ノードは読ませない。
+
+## 確認項目
+
+### 1. 提案の必須項目
+
+子の一覧と責任 / seam / 親に残すもの / 受け入れ条件の割り当て / 子ごとの振り分け /
+他の切り方との比較。1つでも欠けたら**判定不能**として差し戻す。
+
+「親に残すもの」は**項目名の列挙では足りない**。子が独立に決められる程度に、内容が
+書かれているかを見る。
+
+親ノードの内容に人間の**決定の承認**が無い場合も判定不能とする。
+
+### 2. 深さの整合性
+
+- 深さ0の子が課題になっているか
+- 深さ1の子が解決法になっているか
+- 深さ2の子が具体的なシステムになっているか
+- 深さ3をさらに分割していないか
+- interview / split / precheck / review / implement のようなハーネスの役割を子にしていないか
+- **子が1つであることを理由に「分割しない」としていないか**（深さ0-2は子が1つでも分割する）
+- 子が親の決定を詳細化しているか。**選び直していないか**
+- **子ごとの振り分け**が全ての子について書かれているか（責任 / 詳細化の対象 /
+  継承する制約 / 割り当てられた受け入れ条件 / `uses_seams` / 親の決定の版参照）
+
+### 3. seam の数え落とし
+
+一番起きる誤りなので必ず見る。
+
+- 子が**同じファイル・同じ節を書く**なら、それは受け渡しではなく共有状態である
+- 共有状態があるなら、書き込み権限と状態遷移が親へ上がっているか
+- 幸せな道の受け渡しだけを数えていないか（却下・再提案・競合・失効の経路）
+
+### 4. 受け入れ条件の割り当て
+
+未割り当てが残っていないか。残すなら `deferred` として、理由と**再開条件**が
+書かれているか。担当がいるように見せかけていないか。
+
+### 5. 兄弟の不可視性
+
+各子が、兄弟の設計書を読まずに成立するか。親の seam だけで足りるか。
+
+### 6. 自己適用
+
+**その分割自体が、分割基準を満たしているか。**基準を作った側が自分に適用し忘れる。
+
+### 7. 文書間の矛盾
+
+決定を1か所だけ直して他を放置していないか。`harness/` 内と、祖先チェーンの記述。
+
+### 8. 予算
+
+深さ3・子数5の範囲内か。
+
+## 出力
+
+```md
+### precheck <日付> by <確認者>
+
+重大:
+- <指摘>
+
+軽微:
+- <指摘>
+
+判定: 承認推奨 / 修正のうえ再提案 / 判定不能
+```
+
+対象ノードの `index.md` の分割提案の下へ追記する。人間はこれを見て承認を決める。
+
