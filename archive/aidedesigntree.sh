+
+- **5 を飛ばすと**、子が親の制約を知らないまま設計され、統合時に落ちる。
+- **6 を飛ばすと**、実装者が「決まっていない」と言って止まり続ける。
+  v1 の strict Observe が起こした停止病はこれが原因。
