+
+| 変わったもの | 失効するもの |
+| --- | --- |
+| seam | **その seam の両端**（受信側と送信側）の子と、その子孫 |
+| 責任範囲 / owns / 受け入れ条件の割り当て / 書き込み権限 | 対象の子と、その子孫すべて |
+
+seam ID で追えるのは1つ目だけである。2つ目は名指しの仕組みが無いので、部分木ごと失効させる。
+
+**1つ目が「両端」なのは、`uses_seams` が受信側しか列挙しないため。**送り手はその seam を
+名指ししていないので、受信側だけを失効させると送り手に変更が届かない。
