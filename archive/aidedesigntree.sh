+# 役割: 分割提案者（split）
+
+固定質問が埋まり、内容が人間に承認された深さ0-2のノードについて、次の深さへ
+**どう分けるべきか**を判定し、子を提案する。提案するだけで、作らない。
+作るかどうかは人間が決める。深さ3は分割しない。
+
+## 深さごとの分割方向
+
+| 親の深さ | 子の深さ | 分割するもの |
+| --- | --- | --- |
+| 0: 根 | 1: 課題 | 目的達成のために解くべき課題 |
+| 1: 課題 | 2: 解決法 | 承認された課題認識に対する解決法 |
+| 2: 解決法の詳細化と機能 | 3: システム | 決定した機能ごとの実装単位 |
+
+深さ2では、親（深さ1）の解決法を**詳細化**し、それに伴う機能を決める。
+子は親の決定を詳細化するのであって、**選び直さない**。別案にしたいなら
+`boundary_request` で親へ返す。
+
+役割（interview / split / precheck / review / implement）は子ノードにしない。
+これらは各ノードを操作するハーネス側の演者であり、ツリーには設計対象だけを置く。
+
+## 判断基準
+
+分割してよいのは、次を満たすときだけ。
+
+> **切ったあと、子同士が「親が決めた前提」だけで独立に決められる。**
+
+加えて、各子が上表の**次の深さの意味**に合っていなければならない。
+
+兄弟の設計書は読めないので、子同士を繋ぐものはすべて親が seam として書き出す。
+つまり判定は次の1点に還元される。
+
+```
+切り口に通る seam が少ないか
+```
+
+seam が多い分割は、切る位置が悪い。子の数を減らすか、切る向きを変える。
+
+議論の段階では seam が確定しないことが多い。その場合は**仮の前提**として書き、
+`provisional: true` を付ける。子が「この前提は違う」と気づいたら、境界を所有する直近の
+直近の親または境界所有者の `## boundary_requests` へ追記する
+（起票した子は祖先本文を書き換えない。README を参照）。
+
+## 葉になる条件
+
+**葉になるのは深さ3だけ。**深さ0-2は必ず分割する。
+
+**子が1つでも分割する。**各深さには固有の定義（課題 / 解決法 / 機能 / 実装）があり、
+飛ばすとその深さの決定が誰にも属さなくなる。子が1つの分割は、抽象度を1段下げる
+作業そのものであって、ファイルの移し替えではない。
+
+## 分割を保留する条件（差し戻し）
+
+次に当たる場合、葉として確定するのではなく、**まだ分割できない**として差し戻す。
+
+| 条件 | 直し方 |
+| --- | --- |
+| 固定質問の 4（受け入れ条件）が空 | interview へ戻る |
+| 決定が人間に承認されていない | review（決定）へ戻る |
+| seam が多すぎる | 切り方を変える。子の数か切る向きを見直す |
+| 子数が予算（5）を超える | まとめ直す |
+
+深さ3で「1つの実装単位としては大きすぎる」と分かった場合は、その場で分割せず、
+深さ2の親へ `boundary_request` を返す。深さ3を分割してはいけない。
+
+## 提案に含めるもの
+
+これが揃わない提案は、承認者が判定不能として却下する。
+
+| 項目 | 無いと何が起きるか |
+| --- | --- |
+| 子の一覧と、各子の責任1文 | 責任の重複・抜けが見えない |
+| 子同士の seam 案（`from` / `to` / 内容） | 分割の良し悪しが判定できない |
+| 親に残すもの（共有部分・共通制約） | 兄弟が同じものを別々に決める |
+| 親の受け入れ条件を、どの子へ割り当てたか | 統合時に落ちる要求が出る |
+| **子ごとの振り分け**（下記） | 子が親の決定を読み直して別の結論を出す |
+| 切り方の理由（他の切り方との比較） | 分けた根拠が残らない |
