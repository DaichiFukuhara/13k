+# 設計ハーネス
+
+AIDE v2 を、アプリケーションではなく**規約と役割**として書いたもの。
+watcher も UI も無い。人間と AI がこの文書に従って動けば、それがハーネスである。
+
+## 原則
+
+- **状態はツリーが持つ。ハーネスは持たない。** 設計ツリーのファイルが唯一の正で、
+  この `harness/` 配下は手順書にすぎない。どのモデル・どのセッションからでも、
+  ツリーを読めば途中から入れる。
+- **ノードはすべて同じ形をしている。** ただし深さには意味がある。
+  深さ0は根（ペイン・目的）、深さ1は課題、深さ2は解決法、深さ3は具体的なシステム。
+  ノードの形式は共通のまま、何を決めるかが深さによって変わる。
+- **見てよいのは、自分と祖先だけ。** 兄弟の設計書は読まない。兄弟との接続は
+  共通の親が seam として持つ。
+- **子は親を直接書き換えない。** 親の修正が必要なら、その親を別チャットで再開して
+  親自身として書き換える。親だけで決められなければ、同じ手順で必要な祖先まで戻る。
+- **1チャット = 1ノード。** 1つのチャットで扱う対象ノードは1つだけ。分割が承認されたら、
+  子は**別のチャットで話す**。同じノードについて複数のチャットが立つことはある
+  （提案と前検査は別チャット）。逆に、1つのチャットが複数ノードを跨ぐことは無い。
+
+## ツリーの形
+
+```
+<root>/
+  index.md                 根
+  <child>/
+    index.md
+    <grandchild>/
+      index.md
+```
+
+ディレクトリがそのまま木。ノードは `index.md` 1枚。ひな型は
+[node-template.md](node-template.md)。
+
+## ファイル一覧
+
+| ファイル | 中身 |
+| --- | --- |
+| このファイル | 原則・深さの定義・フロー・承認・振り分け・別チャット・予算 |
+| [node-template.md](node-template.md) | ノード1枚の形 |
+| [roles/interview.md](roles/interview.md) | 固定質問7つと、深さごとの対象 |
+| [roles/split.md](roles/split.md) | 分割の判定基準・提案と振り分けの書式 |
+| [roles/precheck.md](roles/precheck.md) | 別実装 AI による前検査の確認項目 |
+| [roles/review.md](roles/review.md) | 人間による決定の承認と分割の承認 |
+| [criteria/README.md](criteria/README.md) | 判断の蓄積の仕方 |
+| [criteria/precedents.md](criteria/precedents.md) | これまでの判断と、その後どうなったか |
+
+このファイルと `node-template.md` の2枚で、何をするものかは分かる。
+`roles/` は各工程の実行者向け。
+
+## 深さごとの意味
+
+| 深さ | ノードが表すもの | そのチャットで決めること | 子として作るもの |
+| --- | --- | --- | --- |
+| 0 | 根 | ペイン、目的、利用者、成功条件、不変条件 | 課題 |
+| 1 | 課題 | 課題の具体化と、その課題に対する解決法 | 解決法 |
+| 2 | 解決法 | 親の決定の詳細化と、それに伴う機能 | 機能ごとの実装単位 |
+| 3 | システム | 実装可能な境界、振る舞い、受け入れ条件 | 作らない。実装へ渡す葉 |
+
+固定質問7個は全ノードで同じ形式を使う。ただし質問の対象は深さによって変わる。
+たとえば「これは何を決めるものか」は、深さ1では課題と解決の範囲、深さ2では解決法の
+詳細と機能、深さ3では実装するシステムを指す。
+
+- **葉になるのは深さ3だけ。**深さ0-2は必ず分割する。
+- **子が1つでも分割する。**各深さに固有の定義があり、飛ばすとその深さの決定が
+  どのノードにも属さなくなる。子が1つの分割は、抽象度を1段下げる作業そのものであり、
+  同じ内容の移し替えではない。
+- **子は親の決定を詳細化する。選び直さない。**別案にしたければ `boundary_request`。
+- 深さ3が1つの実装単位として大きすぎたら、その場で分割せず深さ2へ差し戻す。
+
+## フロー
+
+### 1. 根を構成する
+
+1. 固定質問7個に、人間が1問ずつ答える（[roles/interview.md](roles/interview.md)）。
+2. AI が回答を `index.md` に記録し、深さ0の根を構成する。
+3. **根の内容を人間が承認する。** 内容が未承認のまま分割へ進まない
+   （[roles/review.md](roles/review.md)）。
+
+### 2. 根を課題へ分割する
+
+1. AI が根の目的を達成するために解くべき課題を提案する
+   （[roles/split.md](roles/split.md)）。
+2. 課題同士の seam、親に残す前提、受け入れ条件の割り当て、子ごとの振り分けを書く。
+3. 別実装の AI が前検査する（[roles/precheck.md](roles/precheck.md)）。
+4. **人間が分割を承認する。** 承認後だけ深さ1の課題ノードを作る
+   （[roles/review.md](roles/review.md)）。
+
+### 3. 各課題で解決法を決める
+
+1. 課題ごとに別チャットを cold start する。
+2. 課題ノードと祖先の閉包だけを読み、その課題に対する解決法を決める。
+3. **解決法の決定内容を人間が承認する。**
+4. AI が承認済みの決定を、深さ2の解決法ノードへ分割提案する。
+5. 別実装の AI による前検査後、**人間が分割を承認する。**
+
+### 4. 各解決法をシステムへ落とし込む
+
+1. 解決法ごとに別チャットを cold start する。
+2. 親（課題ノード）の決定を詳細化し、それに伴う機能を決める。選び直さない。
+3. **詳細化と機能の決定内容を人間が承認する。**
+4. AI が承認済みの決定を、深さ3のシステムノードへ分割提案する。
+5. 別実装の AI による前検査後、**人間が分割を承認する。**
+
+### 5. 深さ3を実装へ渡す
+
+深さ3は設計ツリーの葉であり、それ以上分割しない。各システムの内容と受け入れ条件を
+人間が承認したあと、将来の実装者（implement）へ渡す。
+
+## 承認の原則
+
+人間の承認は2種類あり、片方で他方を代用しない。
+
+1. **決定の承認**: そのノードに書かれた目的、課題への解決法、システム化の内容を確定する。
+2. **分割の承認**: その決定を、提案された子ノードと seam に分けてよいと確定する。
+
+深さ3は子を作らないため、決定の承認だけを行う。
+
+**提案するのは AI、確認するのは別実装の AI、承認するのは人間**（2026-08-25 決定）。
+演者を役割で固定する。提案した側は承認できない、という原則の現時点での具体形である。
+
+3 は人間の前に置く前検査であり、拒否権は持たない。指摘を付けて人間へ渡すだけで、
+承認するかは人間が決める。**確認する AI は、提案した AI と別実装であること**
+（同じモデルだと同じ見落としをする）。
+
+分割条件と受け入れ条件の案は AI が作るが、決定と分割は毎回人間が承認する。
+人間は個別承認に加えて、[criteria/precedents.md](criteria/precedents.md) で判断基準自体を
+後から覆せる。
+
+## 子の振り分けは親が書く
+
+分割が承認されたら、子ノードを作るのは親であり、**各子の `## 親からの振り分け` は
+親が書く**。子はこの節を書き換えない。
+
+- 責任（1文）
+- 詳細化の対象（親の決定のどの部分を詳細化するのか）
+- 継承する制約（祖先から降りてくる制約・不変条件）
+- 割り当てられた受け入れ条件
+- `uses_seams`
+- 親の決定の版参照（`<node-id>@<日付>-<種別>-<連番>`）
+
+転記が済んで初めて `children-created`。ここが空のまま子チャットを開くと、子は親の
+提案本文を読み直して自分の担当を再解釈することになり、**開くたびに結論が変わる。**
+
+振り分けが間違っていると子が判断した場合、子は自分で直さず `boundary_request` を返す。
+
+## 子は別チャットで話す
+
+分割が承認された時点で、親のチャットは終わる。子ごとに新しいチャットを開く。
+
+- 1チャットの文脈が1ノードに閉じるので、深い木でも文脈が飽和しない
+- **子チャットは cold start する。**会話の続きではなく、ファイルだけで始まる
+- 親を再開するとき（boundary_request の受理など）も、旧チャットを続けずに cold start する。
+  続けると、チャット内にしかない情報がまた生まれる
+
+別チャットにしても、**兄弟不可視性は担保されない**。同じワークスペースのファイルを読める
+ため、規約として禁止しているだけである（読もうと思えば読める）。担保が必要になったら、
+閉包だけを複製した隔離ディレクトリを渡す方式に変える。
+
+子チャットに渡すのはこれだけ。
+
+```
+harness/README.md に従って <ノードのパス> を進めてください。
+閉包（自ノードと祖先チェーンの index.md）を先に読んでください。
+```
+
+これで始められないなら、その原因は**ツリーに書かれていない情報が親のチャットに
+残っていた**ことであり、直すべきはチャットではなくツリーである。
+受け入れ条件「再現」は、毎回ここで検査されることになる。
+
+## 子から親・祖先へ戻す（boundary_requests）
+
+別チャットになると、子が親へ口頭で相談する経路が無くなる。
+不変条件「子は親を書き換えない」に、次の例外を1つだけ置く。
+
+**子孫は、まず修正が必要な直近の親または境界所有者の `## boundary_requests` に追記する。**
+起票した子は祖先の本文を直接書き換えない。対象ノードを別チャットで cold start し、
+そのノードの担当として本文を修正する。
+
+```md
+## boundary_requests
+
+- from: <起票したノードの id> / date: <日付>
+  対象: <動かしたい seam / owns / 責任範囲>
+  理由: <観測した事実と、現状では決められない理由>
+  status: open        # open / accepted / rejected
+```
+
+親のチャットは終わっているので、これは**親を再開する起票**になる。親を直すだけでは
+祖先の目的・制約・seam と整合しない場合は、親からさらにその祖先へ `boundary_request` を
+起票する。必要な最上位の祖先から人間の承認を取り直し、その後に下位へ決定を降ろす。
+
+`open` の起票には次の制限がある。**兄弟情報の迂回路になるため。**
+
+- 書けるのは境界・観測事実・要求だけ。起票元の内部設計を書かない
